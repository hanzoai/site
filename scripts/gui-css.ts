// Write app/gui.css: the whole @hanzo/gui atomic sheet for lib/gui.ts, as a static asset Next fingerprints.
// lib/gui.ts pulls in the @hanzogui graph (Flow source in react-native), so it is bundled first, react-native aliased to
// react-native-web as the Next build does.
import { build } from 'esbuild';
import { writeFileSync, rmSync } from 'node:fs';

const bundle = new URL('../.gui.gen.mjs', import.meta.url);
await build({
  entryPoints: [new URL('../lib/gui.ts', import.meta.url).pathname],
  bundle: true, format: 'esm', platform: 'node', outfile: bundle.pathname, logLevel: 'error',
  external: ['react', 'react-dom', 'react-native'],
  alias: { 'react-native': 'react-native-web' },
});
const { css } = await import(bundle.href);
const sheet = `/* AUTO-GENERATED by scripts/gui-css.ts from lib/gui.ts — DO NOT EDIT. */\n${css()}`;
writeFileSync(new URL('../app/gui.css', import.meta.url), sheet);
rmSync(bundle);
console.log(`app/gui.css regenerated — ${sheet.length.toLocaleString()} bytes`);
